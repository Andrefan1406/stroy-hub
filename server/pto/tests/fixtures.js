// Спецификация с несколькими элементами подряд: строка-название с количеством,
// «Детали» / «Материалы» на один элемент (как лист 63: ППдм 1 — 2 шт., приямок П 1).
function multiElementPage() {
  const x0 = 1100;
  const items = [
    it('Спецификация элементов ППдм 1, приямков П 1', x0 + 150, 1157, 220),
    it('Обозначение', x0 + 145, 1115, 60), it('Наименование', x0 + 319, 1115, 70),
    it('Кол', x0 + 447, 1115, 20), it('.', x0 + 463, 1115, 3), it('ед', x0 + 482, 1115, 10), it('Примечание', x0 + 519, 1115, 70),
    it('Марка', x0 + 51, 1121, 30), it('поз', x0 + 57, 1108, 20),
  ];
  let y = 1077;
  const row = (c, step = 24) => { items.push(...specRow(y, c, x0)); y -= step; };
  // Колонки этой таблицы смещены: пересчитываем левые края под шапку выше.
  const put = (name, kol, prim, oboz) => {
    if (oboz) items.push(it(oboz, x0 + 100, y, oboz.length * 6));
    if (name) items.push(it(name, x0 + 320, y, name.length * 6));
    if (kol) items.push(it(kol, x0 + 449, y, 12));
    if (prim) items.push(it(prim, x0 + 524, y, prim.length * 6));
    y -= 24;
  };
  put('Плита монолитная ППдм 1', '2'); // название и число элементов
  put('Детали');
  put('Арматура ∅10 А 400', null, null, 'ГОСТ 34028-2016');
  put('L= 57,0 м.п.', '1', '35,1 кг', 'ГОСТ 34028-2016');
  put('Материалы');
  put('Бетон С 20/25', '1,0', 'м ³', '212-101-0901');
  put('Приямок П 1', '2');
  put('Материалы');
  put('Бетон кл. С12/15, F100, W4', null, '0,30 м³', '212-101-0608'); // объём в «Примечании»
  void row;
  return { page: 63, items };
}

